const lang = () => (app.getLocale().startsWith('ru') ? 'ru' : 'en');

/** Текст по ключу с подстановкой {имён}. */
function t(key, vars = {}) {
  const text = DICT[lang()][key] ?? DICT.ru[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}

module.exports = { t, lang };
