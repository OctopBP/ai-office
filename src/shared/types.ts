/**
 * Исход задачи — фундамент табеля роли и рефлексии офиса
 * (docs/design/living-office/spec.md §3). Считается из того, что офис и так
 * знает в момент закрытия: кругов ревью, остановок конвейера, отметок автора.
 *
 * 'reverted' — единственный исход, который ставится уже после закрытия: слитую
 * работу человек откатил руками, и надзор заметил, что коммит слияния пропал
 * из основной ветки. Это самый сильный сигнал из всех — не ревьюер вернул,
 * а владелец выбросил.
 */
export type OutcomeKind =
  | 'clean'      // влита с первого одобрения ревьюера (или сделана без ветки)
  | 'reworked'   // влита после возвратов
  | 'stuck'      // конвейер вставал, разбирался офис, менеджер или человек
  | 'failed'     // исполнитель не сдал: лимит ходов, бюджет, ошибка
  | 'cancelled'  // сняли с доски до сдачи
  | 'reverted';  // влили, а потом откатили

export interface TaskOutcome {
  kind: OutcomeKind;
  /** Сколько раз ревьюер возвращал работу. */
  reworks: number;
  /** Сколько раз конвейер вставал — и по проходящим причинам, и по решению. */
  stuck: number;
  /** Критериев всего и сколько из них отметил автор. */
  criteria: { total: number; claimed: number };
  costUsd: number;
  /** От взятия в работу до сдачи. 0 — задачу не начинали. */
  durationMs: number;
  roleId: string;
  /** Имя пакета роли — для репутации на маркете. null — роль заведена руками. */
  package: string | null;
  model: string;
  /** Кто поставил задачу: человек через менеджера или офис себе (§7). */
  origin: 'owner' | 'office';
  at: number;
}

/** Исходы, после которых задача больше не вернётся в работу сама. */
export const OUTCOME_KINDS: OutcomeKind[] = [
  'clean', 'reworked', 'stuck', 'failed', 'cancelled', 'reverted',
];

