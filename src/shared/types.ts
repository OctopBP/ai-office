export type PermissionMode = 'auto' | 'ask-risky' | 'ask-writes' | 'readonly';

/**
 * Внешний MCP-сервер в каталоге офиса: инструменты, которых нет в самом Claude
 * Code, но без которых роль не может делать свою работу.
 *
 * Каталог живёт в настройках офиса, а не в коде: добавить Blender или дать
 * Figma ещё одной роли — это работа, а не правка исходников с перезапуском.
 */
export interface McpServerDef {
  /**
   * Имя сервера в сессии. Из него собираются имена инструментов
   * (`mcp__figma-bridge__get_document`), поэтому менять его так же больно,
   * как id роли: по этим именам записаны и разрешения «всегда разрешать»,
   * и подписки ролей.
   */
  id: string;
  /** Подпись для человека. Пусто — показывается id. */
  title: string;
  transport: 'stdio' | 'http' | 'sse';
  /** stdio: чем поднимать сервер. У http и sse не используется. */
  command: string;
  args: string[];
  /** http и sse: куда ходить. У stdio не используется. */
  url: string;
  /**
   * Переменные окружения (stdio) или заголовки (http и sse).
   *
   * Значением может быть ТОЛЬКО ссылка вида `${NAME}` — она раскрывается из
   * окружения сервера в момент запуска сессии. Класть сюда сам токен нельзя:
   * настройки офиса лежат в файле состояния и целиком уезжают на фронт в
   * каждом снимке, так что записанный здесь ключ утёк бы дважды.
   */
  env: Record<string, string>;
  /**
   * Держать инструменты сервера в промпте с первого хода. Иначе они прячутся
   * за поиском инструментов — а у ролей с урезанным набором поиска нет, и
   * сервер для них выглядит как «инструментов не видно».
   */
  alwaysLoad: boolean;
  /** Выключен: из каталога не исчезает, но в сессии не поднимается. */
  disabled: boolean;
}

/**
 * Что офис узнал о внешнем MCP-сервере от живой сессии.
 *
 * Сам офис серверы не поднимает — их поднимает сессия агента, каждая свою
 * копию. Поэтому статус здесь не «состояние сервера», а последнее, что о нём
 * сообщили: без него отказ инструмента неотличим от неоткрытого плагина, от
 * опечатки в команде и от того, что `uvx` первый раз качает пакет.
 */
export interface McpServerState {
  /** id сервера из каталога офиса. */
  id: string;
  status: 'connected' | 'failed' | 'needs-auth' | 'pending' | 'disabled';
  /** Текст ошибки — только у `failed`. */
  error: string;
  /** Чем сервер представился при подключении. Пусто — не представился. */
  version: string;
  /** Когда узнали, epoch ms. */
  at: number;
  /** Кто сообщил: id сотрудника, в чьей сессии сервер поднимался. */
  agentId: string;
}

/** Поля роли, которые пользователь может менять из UI. */
export interface RoleEditable {
  title: string;
  emoji: string;
  color: string;
  model: string;
  /** null — наследовать режим офиса (Settings.officePermissionMode). */
  permissionMode: PermissionMode | null;
  maxInstances: number;
  isolate: boolean;
  /**
   * Свой потолок ходов сессии этой роли. null — брать лимит офиса
   * (Settings.taskMaxTurns). Ревьюеру хватает десятка ходов, а разработчику
   * на большой задаче не хватает и сотни — общий на офис лимит приходится
   * ставить по самому прожорливому.
   *
   * «Без ограничения» на уровне роли не бывает: снять лимит совсем можно
   * только офису целиком, иначе одно и то же null означало бы то «как в
   * офисе», то «сколько угодно».
   */
  maxTurns: number | null;
  /** Свой репозиторий роли; пусто — общий репозиторий офиса. */
  repoDir: string;
  /**
   * Внешние MCP-серверы роли — id из каталога офиса (`Settings.mcpServers`).
   *
   * В снимке для UI здесь всегда действующий набор: у роли, которой сервера
   * никогда не назначали, это умолчание по её id (дизайнеру — Figma). Правка
   * из редактора кладёт список явно, и пустой список значит именно «ничего не
   * подключать», а не «как у всех».
   */
  mcp: string[];
  /**
   * Внешность агента — идентификатор из `shared/looks.ts` (он же имя скина
   * трёхмерной модели). Пусто — веб подбирает внешность по id роли, как
   * делал до появления поля: у базовых ролей своя внешность нарисована, и
   * затирать её значением по умолчанию нельзя.
   *
   * Поле называется `sprite` с тех пор, когда офис был только плоским, и
   * так лежит в сохранённых состояниях. В них попадаются и старые значения
   * (`agent_p7`) — веб понимает их как спрайт плоского офиса, но выбрать
   * такое заново уже нельзя: комнате нужен скин, а не спрайт.
   */
  sprite: string;
  /**
   * Инструкция роли — системный промпт её сессий. У роли, привязанной к
   * пакету, это вычисленный текст: бриф пакета плюс `briefExtra`. Править
   * его напрямую у такой роли нельзя — форма шлёт `briefExtra`, а патч с
   * `brief` для привязанной роли офис игнорирует.
   */
  brief: string;
  /**
   * Приписка к брифу пакета — то, что человек дописал от себя: стек,
   * соглашения, репозиторий. Клеится снизу к брифу пакета и никогда не
   * конфликтует с его обновлением: пакет и приписка лежат в разных полях.
   * У роли без пакета поле пустое и ни на что не влияет.
   */
  briefExtra: string;
}

