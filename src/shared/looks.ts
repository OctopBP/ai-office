/**
 * Внешности агентов — общий список для сервера и веба.
 *
 * Внешность — это персонаж трёхмерного офиса, то есть скин из
 * `design/models/characters/skins`. Вариантов ровно столько, сколько скинов
 * в наборе: скин — целиком нарисованная художником развёртка, а не набор
 * параметров, который можно домешать. Раньше в форме роли предлагалось
 * десять плоских пресетов, и восемь из них показывали в комнате не то, что
 * было выбрано.
 *
 * Список живёт рядом с самими файлами — `skins/looks.json`, — а не в коде:
 * его правит стенд скинов (`?skins=1`), а стенд не должен уметь переписывать
 * исходники. Здесь только разбор файла и проверка, что в нём нет мусора.
 *
 * `id` — имя файла скина: одно имя вместо пары «идентификатор + файл»,
 * которую пришлось бы держать в согласии руками. `sprite` — чем тот же
 * агент рисуется в плоском офисе (`design/sprites/out`): пиксельные
 * человечки нарисованы отдельно от скинов, и точного соответствия между
 * ними нет — берётся ближайший по виду. `title` — подпись в форме роли на
 * каждом языке; она лежит здесь, а не в словарях веба, потому что вместе со
 * скином её заводит художник, а не переводчик интерфейса. Подпись — одно-два
 * слова про облик («Скейтер», «Бородач»), не длиннее ~14 символов: она стоит
 * под картинкой в карточке выбора и от описательной фразы поехала бы в две
 * строки. Переименовывать `id` ради подписи нельзя — по нему лежат файлы
 * скина и портрета и на него ссылаются уже нанятые агенты.
 *
 * Как добавить внешность: `npm run dev:3d`, дальше `?skins=1` — стенд
 * загрузит файл, покажет его на модели во всех позах и запишет в список.
 * Руками — то же самое: положить png в папку и дописать запись в
 * `looks.json`. Текстуры комната подхватывает из папки целиком, карточки в
 * форме роли раскладываются по длине списка сами.
 */
import registry from '../../design/models/characters/skins/looks.json';
import { parseLooks, type Look } from './look';

export { LOOK_ID, SPRITE_ID, lookTitle, parseLooks, type Look } from './look';

export const LOOKS: Look[] = parseLooks(registry);

/** Внешность по идентификатору; неизвестный — undefined. */
export function lookById(id: string | undefined): Look | undefined {
  return id ? LOOKS.find((l) => l.id === id) : undefined;
}

/** Есть ли такая внешность. Проверка одна на сервер и веб. */
export function isLookId(id: string): boolean {
  return LOOKS.some((l) => l.id === id);
}

/**
 * Какая внешность у агента на самом деле. Выбранная у роли — она; не выбрана
 * (или в поле лежит старое имя спрайта) — по кругу от порядкового номера
 * сотрудника в офисе, чтобы соседи за столами отличались. Правило одно на
 * комнату и аватарки: портрет обязан показывать того же человечка, что
 * сидит за столом.
 */
export function lookFor(roleSprite: string | undefined, index: number): string | undefined {
  if (LOOKS.length === 0) return undefined;
  return lookById(roleSprite)?.id ?? LOOKS[Math.abs(index) % LOOKS.length].id;
}
