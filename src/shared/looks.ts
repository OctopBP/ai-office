/**
 * Внешности агентов — общий список для сервера и веба.
 *
 * Внешность — это персонаж трёхмерного офиса, то есть скин из
 * `design/models/characters/skins`. Вариантов ровно столько, сколько скинов
 * в наборе: скин — целиком нарисованная художником развёртка, а не набор
 * параметров, который можно домешать. Раньше в форме роли предлагалось
 * десять плоских пресетов, и восемь из них показывали в комнате не то, что
 * было выбрано.
 *
 * `id` — имя файла скина: одно имя вместо пары «идентификатор + файл»,
 * которую пришлось бы держать в согласии руками. `sprite` — чем тот же
 * агент рисуется в плоском офисе (`design/sprites/out`): пиксельные
 * человечки нарисованы отдельно от скинов, и точного соответствия между
 * ними нет — берётся ближайший по виду.
 *
 * Как добавить внешность:
 *
 *  1. положить текстуру в `design/models/characters/skins/` — развёртка
 *     должна быть от того же персонажа (набор Kenney «Animated Characters
 *     Protagonists»), иначе она ляжет на модель не теми кусками;
 *  2. дописать строку в `LOOKS`: `id` — имя файла без расширения,
 *     `sprite` — ближайший по виду человечек плоского офиса;
 *  3. добавить подпись `look.<id>` в оба словаря веба (`src/web/i18n`).
 *
 * Больше нигде ничего трогать не надо: текстуры подхватываются из папки
 * целиком, карточки в форме роли раскладываются по длине списка сами, а
 * сервер проверяет выбор ролью по этому же списку.
 */
export interface Look {
  /** Имя скина в `design/models/characters/skins` — оно же значение `RoleEditable.sprite`. */
  id: string;
  /** Спрайт плоского офиса из каталога (`agent_p1`…`agent_p10`). */
  sprite: string;
}

export const LOOKS: Look[] = [
  { id: 'boss', sprite: 'agent_p3' },
  { id: 'skaterMaleA', sprite: 'agent_p4' },
  { id: 'skaterFemaleA', sprite: 'agent_p10' },
  { id: 'cyborgFemaleA', sprite: 'agent_p1' },
  { id: 'criminalMaleA', sprite: 'agent_p2' },
];

/** Внешность по идентификатору; неизвестный — undefined. */
export function lookById(id: string | undefined): Look | undefined {
  return id ? LOOKS.find((l) => l.id === id) : undefined;
}

/** Есть ли такая внешность. Проверка одна на сервер и веб. */
export function isLookId(id: string): boolean {
  return LOOKS.some((l) => l.id === id);
}
