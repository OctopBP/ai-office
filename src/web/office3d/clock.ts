/**
 * Часы сцены: сколько она прожила на экране и на экране ли она сейчас.
 *
 * Модуль, а не состояние компонента и не стор, — по тем же причинам, по каким
 * рядом лежат якоря камеры (`anchors.ts`): это ответ на вопрос кадра, менять
 * из-за него разметку незачем, а переживать смену вида он обязан.
 *
 * Зачем свои часы. Пока вид офиса скрыт, кадровый цикл выключен
 * (`frameloop="never"` в `Office3D.tsx`), а собственные часы R3F при каждом
 * таком переключении обнуляются: `setFrameloop` в @react-three/fiber делает
 * `clock.stop(); clock.elapsedTime = 0`. Всё, что считалось от
 * `state.clock.elapsedTime`, после возврата начиналось заново — очередь в
 * разговоре, например, разом менялась ролями. Здесь время растёт по длине
 * кадра и только пока кадры идут, поэтому уход на доску и возврат его не
 * сбивают: анимация продолжается с того же места.
 *
 * Зачем признак «на экране» лежит здесь, а не ходит пропсом. Спрятанная сцена
 * стоит в `display: none`, её измеренный размер — нули, а R3F перерисовывает
 * дерево сцены только при ненулевом размере (`Canvas` в react-three-fiber:
 * `if (containerRect.width > 0 && containerRect.height > 0)`). Пропсы из
 * `Office3D` в это время до агентов не доходят — а подписки на стор внутри
 * сцены работают как обычно. Значит, признак должен приходить не пропсом.
 */

/** Секунды, накопленные кадрами. Растут только пока офис на экране. */
let seconds = 0;

/** Вид офиса показан. До первого кадра считаем, что да: сцена монтируется
 *  вместе с видом. */
let onScreen = true;

/**
 * Самый длинный кадр, который сцена считает кадром.
 *
 * Вкладка в фоне — кадров нет, а часы браузера идут: первый кадр после
 * возврата приходит «длиной» в минуту. Без ограничения он проносит фигуру
 * через полкомнаты одним шагом и мгновенно докручивает все плавности — ровно
 * то дёрганье, из-за которого возврат выглядит поломкой. Столько же берёт себе
 * риг камеры (`Camera3D.tsx`).
 */
export const MAX_DT = 0.1;

/** Кадр прошёл: время сцены выросло ровно на его длину. */
export function tickScene(dt: number): void {
  seconds += dt;
}

/** Сколько секунд сцена прожила на экране. */
export function sceneTime(): number {
  return seconds;
}

/** Вид офиса показан или скрыт — говорит оболочка через `Office3D`. */
export function setSceneOnScreen(on: boolean): void {
  onScreen = on;
}

/** Идут ли сейчас кадры: скрытая сцена их не считает. */
export function sceneOnScreen(): boolean {
  return onScreen;
}
