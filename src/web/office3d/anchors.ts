/**
 * Где сейчас стоит каждый агент — доска объявлений между человечками и
 * камерой.
 *
 * Стор для этого не годится. Позиция агента меняется каждый кадр (её ведёт
 * `useFrame` в `Agents3D`), а стор — это React: запись в него перерисовывает
 * подписчиков, и слежение камеры за идущим человеком превратилось бы в
 * шестьдесят перерисовок офиса в секунду. В сторе лежит и всегда лежала
 * только цель — «иди туда за столько миллисекунд»; сколько агент прошёл на
 * самом деле, знает объект сцены, и здесь у него просто спрашивают.
 *
 * Координаты мировые (тайлы, сдвиг комнаты уже учтён) — камере они нужны
 * именно такими, а не в системе плана.
 */
import * as THREE from 'three';

const anchors = new Map<string, THREE.Vector3>();

/** Куда встал агент в этом кадре. Копируется, а не запоминается ссылкой:
 *  снаружи это позиция живой группы, и её меняют дальше по кадру. */
export function setAnchor(id: string, p: THREE.Vector3): void {
  const cur = anchors.get(id);
  if (cur) cur.copy(p);
  else anchors.set(id, p.clone());
}

/** Агент ушёл из сцены (сменилась раскладка, распустили команду). */
export function dropAnchor(id: string): void {
  anchors.delete(id);
}

/**
 * Где агент. `undefined` — не «его нет», а «в этом кадре ещё неизвестно»:
 * фигура могла не успеть смонтироваться. Камере это важно различать — на
 * такой ответ она просто не двигается, вместо того чтобы ехать в ноль.
 */
export function anchorOf(id: string): THREE.Vector3 | undefined {
  return anchors.get(id);
}
