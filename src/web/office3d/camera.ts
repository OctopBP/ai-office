/**
 * Фокус камеры — на что она сейчас смотрит.
 *
 * До этого камера смотрела в одну точку навсегда: цель облёта была прибита к
 * началу координат, а панорамирование выключено. Пока офис разглядывали
 * целиком, это было даже правильно — комната вписана в кадр, крути да
 * смотри. Но стоит приблизиться, и дальше центра опенспейса не уехать:
 * колесо тянет камеру по лучу в одну и ту же точку, и кухня с переговоркой
 * остаются за кадром.
 *
 * Поэтому цель стала подвижной, а «фокус» — это то, кто ею распоряжается:
 *
 *  - `overview` — вся раскладка, вписанная в кадр (прежнее поведение);
 *  - `room` — одна комната раскладки;
 *  - `agent` — выбранный человек, за которым камера едет, пока он идёт;
 *  - `free` — цель у пользователя: он увёл её панорамированием, стрелками
 *    или колесом, и камера в неё не вмешивается.
 *
 * Угол облёта фокус не трогает вовсе: и вращение, и наезд колесом остаются
 * за пользователем в любом режиме. Фокус отвечает на вопрос «куда смотрим»,
 * а не «откуда».
 *
 * Отдельный стор, а не поле в общем: это состояние камеры одного рендера, а
 * не офиса, — оно не едет на сервер, не переживает перезагрузку и не должно
 * перерисовывать половину приложения.
 */
import { create } from 'zustand';
import type { Layout } from '../../shared/layout';
import { t, type UiKey } from '../i18n';

export type Focus =
  | { kind: 'overview' }
  | { kind: 'free' }
  | { kind: 'room'; id: string }
  | { kind: 'agent'; id: string };

interface CameraState {
  focus: Focus;
  setFocus: (f: Focus) => void;
}

export const useCamera = create<CameraState>((set) => ({
  focus: { kind: 'overview' },
  setFocus: (focus) => set({ focus }),
}));

/** Названия комнат для чипов и подписей. Раскладка вправе дать своё
 *  (`LayoutRoom.title`), эти — запасные для комнат из пресетов. */
const ROOM_KEYS: Record<string, UiKey> = {
  meeting: 'room.meeting',
  lounge: 'room.lounge',
  open: 'room.open',
};

export function roomTitle(room: { id: string; title?: string }): string {
  // Комнаты пресетов узнаются по id, и их названия — часть приложения:
  // на них завязаны чипы фокуса и горячие клавиши. Название из файла
  // остаётся у комнаты, которой в этом словаре нет.
  const key = ROOM_KEYS[room.id];
  return key ? t(key) : (room.title ?? room.id);
}

/** Комнаты, на которые можно навестись. Раскладка без комнат (`classic`)
 *  даёт пустой список — фокусироваться там не на чем, и чипов не будет. */
export function focusRooms(layout: Layout) {
  return layout.rooms ?? [];
}
