/**
 * Подгонка — числа, которыми фигура садится за мебель.
 *
 * Раньше эти числа были константами, разбросанными по трём файлам, и каждое
 * подбиралось вслепую: «сдвинь на десять сантиметров, пересобери, посмотри».
 * Здесь они собраны в один файл данных (`design/fit.json`), правятся стендом
 * (`?fit=1`) на живой сцене и уезжают в гит обычным диффом.
 *
 * Делятся они на два сорта, и путать их нельзя:
 *
 * — **измеряемое**: высота сиденья у модели стула, высота таза в клипе,
 *   длина шага. Это факты; они считаются из ассетов при загрузке
 *   (`measure.ts`) и меняются сами, когда меняют модель или клип. В файле
 *   таких чисел нет — есть только `null` там, где можно принудительно задать
 *   своё вместо измеренного;
 *
 * — **вкусовое**: насколько таз выше плоскости сиденья, насколько кисти выше
 *   столешницы, каким видимым масштабом рисовать набор мебели. Это решения,
 *   их измерить неоткуда, и живут они здесь.
 *
 * Значения в тайлах (тайл — 0.75 м), как и вся остальная геометрия сцены.
 */
import { create } from 'zustand';
import raw from '../../../design/fit.json';

/** Чем поза цепляется за место. */
export type Anchor = 'feet' | 'hips';

export interface PoseFit {
  /**
   * Стоячие позы ставятся ступнями на пол, сидячие — тазом на плоскость
   * сиденья. Это не одно и то же смещение с разным знаком: у сидячей позы
   * расстояние от таза до ступней зависит от клипа, и ставить её ступнями
   * значит утопить таз в стуле ровно на эту разницу.
   */
  anchor: Anchor;
  /** Поправка к якорю: вправо, вверх, вперёд. */
  offset: [number, number, number];
  /** Тянуть ли кисти к рабочей поверхности (IK). Только там, где поверхность есть. */
  reach?: boolean;
}

export interface PlaceFit {
  /** Поправка к точке посадки за этим предметом: вправо, вверх, вперёд. */
  seat: [number, number, number];
  /** Высота рабочей поверхности вместо измеренной по модели; null — мерить. */
  surface?: number | null;
}

export interface Fit {
  version: number;
  figure: {
    /** Рост фигуры в тайлах. */
    tall: number;
    /**
     * Видимый масштаб набора мебели, множителем к `MODEL_SCALE`.
     *
     * Ручка существует потому, что настоящая развилка проекта — не «куда
     * сдвинуть человечка», а «кто под кого подгоняется». Персонаж Kenney
     * сложён по-мультяшному: короткие ноги, большая голова, — и мебель,
     * построенная по человеческим размерам, ему сидя велика примерно на
     * двадцать сантиметров. Уменьшить набор — один из трёх ответов.
     *
     * Меняет только то, что видно. След предмета, проходимость и посадочные
     * места считаются по каталогу и остаются прежними: выбрав масштаб не
     * единицу, каталог придётся пересчитать.
     */
    furniture: number;
  };
  walk: {
    /** Скорость агента по офису, тайлов в секунду (её же читает стор). */
    tilesPerSec: number;
    /** Скорость шага в клипе вместо измеренной; null — мерить по клипу. */
    clipSpeed: number | null;
  };
  seated: {
    /**
     * Насколько таз выше плоскости сиденья. У человека это не ноль: тазовая
     * кость сидит выше точек опоры примерно на ладонь.
     */
    hipsOverSeat: number;
    /** Насколько кисти выше столешницы, когда лежат на ней. */
    handsOverSurface: number;
    /** Тянуть кисти к столешнице обратной кинематикой. */
    ik: boolean;
    /** Сила подтягивания: 0 — как в клипе, 1 — точно на поверхность. */
    ikWeight: number;
  };
  poses: Record<string, PoseFit>;
  places: Record<string, PlaceFit>;
}

/** Пределы ползунков стенда — они же границы, по которым чинится файл. */
export const FIT_RANGE = {
  tall: { min: 1.5, max: 3.5, step: 0.01 },
  furniture: { min: 0.5, max: 1.5, step: 0.005 },
  tilesPerSec: { min: 0.5, max: 8, step: 0.1 },
  // Нижний край не случайный: −0.26 тайла — это ровно та высота, на которой
  // у сидящего ступни встают на пол. Ползунок должен доставать до обоих
  // концов развилки: «таз на подушке» и «ноги на полу».
  hipsOverSeat: { min: -0.45, max: 0.4, step: 0.005 },
  handsOverSurface: { min: -0.2, max: 0.3, step: 0.005 },
  ikWeight: { min: 0, max: 1, step: 0.05 },
  offset: { min: -1, max: 1, step: 0.005 },
} as const;

/**
 * Файл на диске — источник умолчаний. Читается импортом, а не запросом:
 * так он попадает в сборку вместе с раскладками и каталогом, и офис в
 * проде не зависит от того, лежит ли рядом `design/`.
 *
 * Правка файла руками перезагружает страницу через HMR — стенд для этого не
 * обязателен, числа можно править и в редакторе.
 */
export const FILE_FIT = raw as unknown as Fit;

/**
 * Живые числа подгонки.
 *
 * Отдельный стор, а не поле в общем: подгонка — свойство ассетов, а не
 * состояния офиса; она не едет на сервер, не пишется в стейт-файл и не
 * должна перерисовывать пол-приложения при движении ползунка.
 */
interface FitState {
  fit: Fit;
  /** Правка ползунком: меняет только то, что передали. */
  patch: (edit: (fit: Fit) => Fit) => void;
  /** Вернуться к тому, что лежит в файле. */
  revert: () => void;
}

export const useFit = create<FitState>((set) => ({
  fit: FILE_FIT,
  patch: (edit) => set((s) => ({ fit: edit(structuredClone(s.fit)) })),
  revert: () => set({ fit: FILE_FIT }),
}));

/** Числа подгонки вне React — сторy и замерам они нужны без хука. */
export function fitNow(): Fit {
  return useFit.getState().fit;
}

/** Настройки позы; неизвестная поза ставится ступнями и без поправок. */
export function poseFit(fit: Fit, pose: string): PoseFit {
  return fit.poses[pose] ?? { anchor: 'feet', offset: [0, 0, 0] };
}

/** Настройки места; предмет без своей строки — без поправок. */
export function placeFit(fit: Fit, sprite: string | undefined): PlaceFit {
  return (sprite ? fit.places[sprite] : undefined) ?? { seat: [0, 0, 0] };
}

/**
 * Записать числа в `design/fit.json`.
 *
 * Пишет дев-сервер (плагин в `vite.config.ts`), потому что писать в
 * `design/` из браузера больше некому, а сервер офиса про ассеты ничего не
 * знает и знать не должен. В сборке этого маршрута нет — и не нужно: стенд
 * тоже только в деве.
 */
export async function saveFit(fit: Fit): Promise<void> {
  const res = await fetch('/__fit', {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify(fit, null, 2),
  });
  if (!res.ok) throw new Error(`не записалось: ${res.status} ${await res.text()}`);
}
