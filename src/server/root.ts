/**
 * Корень, от которого сервер читает свои файлы: пакеты ролей, процессы,
 * раскладки офиса, каталог спрайтов, реестр маркета, свои mcp-инструменты.
 *
 * Из исходников это папка репозитория — две ступени вверх от `src/server`.
 * В приложении исходников нет вовсе: те же файлы лежат в ресурсах рядом с
 * собранным сервером, и путь к ним приходит переменной. Считается это в одном
 * месте, потому что раньше та же пара строк стояла в шести файлах — и стоило
 * переехать одному, как остальные читали из пустоты.
 */

import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = process.env.OFFICE_ROOT
  ? resolve(process.env.OFFICE_ROOT)
  : resolve(dirname(fileURLToPath(import.meta.url)), '../..');
